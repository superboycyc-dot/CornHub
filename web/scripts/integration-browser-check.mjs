import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
page.setDefaultTimeout(15000);
const errors=[];page.on('pageerror', e=>errors.push(e.message));
await page.goto('http://localhost:5173',{waitUntil:'domcontentloaded'});
await page.getByRole('combobox',{name:'Field',exact:true}).selectOption('barc_1');
await page.getByLabel('Year',{exact:true}).selectOption('2023');
await page.getByLabel('Prediction role',{exact:true}).selectOption('oof');
if (!(await page.getByLabel('Field panel').isVisible())) await page.getByRole('button',{name:'Field',exact:true}).click();
await page.getByLabel('Field panel').getByText('rf_v1_uncalibrated',{exact:true}).waitFor();
const source=JSON.parse(await fs.readFile('../reports/e_web/handoff-verification.json','utf8'));
const realPanel=await page.getByLabel('Field panel').innerText();
assert.ok(realPanel.includes('uncalibrated'));
await page.waitForTimeout(400);
await page.screenshot({path:'../reports/e_web/integration-real-desktop.png', animations:'disabled'});
await page.getByRole('button',{name:'Close panel'}).click();
const polygon=page.locator('path[aria-label^="Field barc_1, 2023, oof,"]').first();
await polygon.focus();await page.locator('.field-hover').filter({has:page.locator('.tooltip-title',{hasText:/^barc_1$/})}).waitFor({state:'visible'});
assert.ok((await page.locator('.field-hover').filter({has:page.locator('.tooltip-title',{hasText:/^barc_1$/})}).innerText()).includes('barc_1'));
await polygon.press('Enter');await page.getByLabel('Field panel').waitFor();
await page.getByRole('button',{name:'Close panel'}).click();
await page.getByRole('button',{name:'Analysis',exact:true}).click();
assert.ok((await page.getByLabel('Analysis panel').innerText()).includes('40.63679195'));
await page.getByLabel('Year',{exact:true}).selectOption('2024');
assert.ok((await page.getByLabel('Analysis panel').innerText()).includes('Not computed'));
await page.getByRole('button',{name:'Review',exact:true}).click();
const review=await page.getByLabel('Review panel').innerText();
assert.ok(!review.includes('barc_'));
await page.getByLabel('Year',{exact:true}).selectOption('2023');
await page.getByLabel('Prediction role',{exact:true}).selectOption('inference');
assert.ok(!(await page.getByLabel('Review panel').innerText()).includes('barc_'));
await page.getByLabel('Prediction role',{exact:true}).selectOption('oof');
await page.setViewportSize({width:390,height:844});
if (!(await page.getByLabel('Field panel').isVisible())) await page.getByRole('button',{name:'Field',exact:true}).click();
await page.waitForTimeout(400);
await page.screenshot({path:'../reports/e_web/integration-real-mobile.png', animations:'disabled'});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
await fs.writeFile('../reports/e_web/integration-browser-verification.json',JSON.stringify({status:'passed',real_data:true,boundaries:source.boundary_count,labels:source.label_year_count,checks:['real 2023 OOF model displayed','field keyboard focus tooltip and Enter selection','2023 D area shown','2024 pending area','2024 no stale review queue','inference no OOF review queue','390px mobile no horizontal overflow','no JavaScript page errors'],screenshots:['integration-real-desktop.png','integration-real-mobile.png'],note:'Local Chromium acceptance; no production deployment or external basemap availability guarantee.'},null,2)+'\n');
await browser.close();console.log('Real-data browser integration checks passed');
